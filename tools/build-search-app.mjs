#!/usr/bin/env node
/**
 * build-search-app.mjs
 *
 * Projects graph/fusion-graph.json into the shape the Graph Explorer app wants
 * (app/data.js), then optionally inlines index.html + app.css + app.js + data.js
 * into one shareable, dependency-free HTML file.
 *
 * Usage:
 *   node tools/build-search-app.mjs [--graph <path>] [--bundle]
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const arg = (n, d) => {
  const i = argv.indexOf(n);
  return i !== -1 && argv[i + 1] ? argv[i + 1] : d;
};
const HERE = path.dirname(new URL(import.meta.url).pathname);
const KG_ROOT = path.resolve(HERE, '..');
const GRAPH = path.resolve(arg('--graph', path.join(KG_ROOT, 'graph/fusion-graph.json')));
const APP = path.join(KG_ROOT, 'app');

const graph = JSON.parse(fs.readFileSync(GRAPH, 'utf8'));

/** Credit shown in the status bar of the explorer. */
const AUTHOR = {
  name: 'Baig Mohammed',
  linkedin: 'https://www.linkedin.com/in/mbaig162/',
};

/**
 * UPL-1.0 permits redistributing this derived data, on the condition that the
 * copyright notice travels with it. The app renders this in its status bar, so
 * the requirement is met wherever the page is hosted.
 */
const ATTRIBUTION = {
  text: 'Data derived from oracle/fusion-ai-studio · UPL-1.0',
  href: 'https://github.com/oracle/fusion-ai-studio',
};

// ---------------------------------------------------------------- project nodes

/** Fields the app reads. Everything else is dropped to keep data.js lean. */
const KEEP = [
  'id', 'label', 'type', 'code', 'summary', 'nodeType', 'workflow', 'family', 'product',
  'status', 'architecture', 'pagePattern', 'agentCount', 'nodeCount', 'rawNodeEntries',
  'aiAppsCompatible', 'operationType', 'resourcePath', 'restResourcePath', 'objectSource',
  'toolType', 'namespace', 'usageType', 'destinationUrl', 'verb', 'group', 'modelName',
  'provider', 'lines', 'triggers', 'inputNames', 'params', 'seeded', 'issues',
  'source_file', 'sourceCodeLines', '_stub',
  // metrics from tools/compute-graph-metrics.mjs
  'pagerank', 'pagerankRank', 'betweenness', 'bridgeScore', 'blastRadius',
  'community', 'communitySize', 'componentId', 'clustering', 'articulation',
  'degree', 'inDegree', 'outDegree',
  // Agent Studio stack position
  'layer', 'layerName', 'stackRole', 'appExposed',
  // the authoring corpus
  'corpusRole', 'corpusHalf', 'promptRole', 'modality', 'marker', 'body', 'owner',
  'section', 'parent', 'level', 'ruleCount', 'specified', 'specFile', 'instanceCount',
  'kind', 'skill',
  // supported-tool-type classification
  'toolTypeKey', 'toolTypeName', 'toolTypeSource', 'supportedSince', 'artifactCount', 'usedHere',
  // Oracle console section, provenance, and .agent specifics
  'studioSection', 'origin', 'agentKind', 'reusable', 'namespace', 'maxInteractions', 'component',
];

const nodes = graph.nodes.map((n) => {
  const o = {};
  for (const k of KEEP) if (n[k] !== undefined && n[k] !== null && n[k] !== '') o[k] = n[k];
  // a rule's summary is a truncated copy of its body; shipping both doubles the
  // single largest node type in the payload for nothing
  if (n.type === 'rule') delete o.summary;
  // renamed for brevity in the payload; the app reads these names
  if (n.promptExcerpt) o.prompt = n.promptExcerpt;
  if (n.caseExpression) o.expr = n.caseExpression;
  if (n.sourceCodeExcerpt) o.src = n.sourceCodeExcerpt;
  // one extra searchable blob so full text hits prompts and code
  const body = [n.promptExcerpt, n.caseExpression, n.sourceCodeExcerpt, n.resourcePath, n.destinationUrl]
    .filter(Boolean)
    .join(' ');
  if (body) o.body = body;
  return o;
});

const edges = graph.edges.map((e) => {
  const o = { source: e.source, target: e.target, relation: e.relation };
  if (e.context && e.context !== 'success') o.context = e.context;
  return o;
});

const payload = {
  generatedAt: new Date().toISOString(),
  repoUrl: 'https://github.com/oracle/fusion-ai-studio/blob/release-26C',
  author: AUTHOR,
  attribution: ATTRIBUTION,
  counts: graph._meta?.counts ?? {},
  metrics: graph._meta?.metrics ?? {},
  layers: graph._meta?.layers ?? {},
  toolTypes: graph._meta?.toolTypes ?? {},
  authoring: graph._meta?.authoring ?? {},
  corpusRoles: graph._meta?.corpusRoles ?? {},
  studioSections: graph._meta?.studioSections ?? {},
  nodes,
  edges,
};

fs.mkdirSync(APP, { recursive: true });
const dataJs = `/* generated by tools/build-search-app.mjs — do not edit */\nwindow.FUSION_GRAPH = ${JSON.stringify(payload)};\n`;
fs.writeFileSync(path.join(APP, 'data.js'), dataJs);

const kb = (b) => `${(b / 1024).toFixed(0)} KB`;
console.log(`[app] data.js  ${nodes.length} nodes, ${edges.length} edges  (${kb(Buffer.byteLength(dataJs))})`);

// ---------------------------------------------------------------- optional single-file bundle

if (argv.includes('--bundle')) {
  const html = fs.readFileSync(path.join(APP, 'index.html'), 'utf8');
  const css = fs.readFileSync(path.join(APP, 'app.css'), 'utf8');
  const js = fs.readFileSync(path.join(APP, 'app.js'), 'utf8');
  // `</script>` inside a string literal would close the inlined tag early
  const safe = (s) => s.replace(/<\/script>/gi, '<\\/script>');
  // The replacement MUST be a function. With a string, `$\``, `$'` and `$&` are
  // substitution patterns, not literals — and the corpus contains them for real
  // (a rule stating that workflow codes match `^[A-Z0-9_]+$`, quoted in
  // backticks, is a `$\`` the moment it lands in data.js). That silently spliced
  // the whole document back into itself ten times over.
  const inline = (tag, body) => (h) => h.replace(tag, () => body);
  const bundled = [
    inline('<link rel="stylesheet" href="app.css">', `<style>\n${css}\n</style>`),
    inline('<script src="data.js"></script>', `<script>\n${safe(dataJs)}\n</script>`),
    inline('<script src="app.js"></script>', `<script>\n${safe(js)}\n</script>`),
  ].reduce((h, f) => f(h), html);
  const out = path.join(APP, 'agent-stack-explorer.html');
  fs.writeFileSync(out, bundled);
  console.log(`[app] bundle   ${out}  (${kb(Buffer.byteLength(bundled))}, self-contained)`);
}

// ---------------------------------------------------------------- static site

if (argv.includes('--site')) {
  const SITE = path.resolve(arg('--site-dir', path.join(KG_ROOT, 'docs')));
  fs.mkdirSync(SITE, { recursive: true });
  for (const f of ['index.html', 'app.css', 'app.js']) {
    fs.copyFileSync(path.join(APP, f), path.join(SITE, f));
  }
  fs.writeFileSync(path.join(SITE, 'data.js'), dataJs);
  // GitHub Pages runs Jekyll by default, which skips files beginning with _
  fs.writeFileSync(path.join(SITE, '.nojekyll'), '');
  const bytes = ['index.html', 'app.css', 'app.js', 'data.js']
    .reduce((a, f) => a + fs.statSync(path.join(SITE, f)).size, 0);
  console.log(`[app] site      ${SITE}  (${kb(bytes)} across 4 files, gzips to ~10% over the wire)`);
}

console.log(`[app] open:     file://${path.join(APP, 'index.html')}`);
